package com.claudecode.core.message;

import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

class MessageFactoryModelSwitchTest {

    @Test
    void modelSwitchBreadcrumbsMatchReleased197CommandTagsExactly() {
        List<UserMessage> breadcrumbs = MessageFactory.createModelSwitchBreadcrumbs(
            "claude-opus-4-6", "claude-opus-4-6");

        assertEquals(3, breadcrumbs.size());
        assertTrue(breadcrumbs.getFirst().isMeta());
        assertEquals(
            "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. "
                + "DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to."
                + "</local-command-caveat>",
            breadcrumbs.getFirst().message().text());
        assertEquals(
            """
            <command-name>/model</command-name>
                        <command-message>model</command-message>
                        <command-args>claude-opus-4-6</command-args>""",
            breadcrumbs.get(1).message().text());
        assertEquals(
            "<local-command-stdout>Set model to claude-opus-4-6</local-command-stdout>",
            breadcrumbs.get(2).message().text());
    }
}
