package com.claudecode.tools.cron;


import com.claudecode.core.state.CwdState;

import com.claudecode.core.git.GitUtils;

import org.apache.commons.lang3.StringUtils;
import com.claudecode.core.serialization.JsonUtils;
import com.fasterxml.jackson.databind.node.ObjectNode;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.nio.file.StandardOpenOption;
import java.time.Instant;
import java.util.*;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.function.Predicate;

/**
 * In-memory (+ optional durable) cron job store shared by CronCreateTool / CronDeleteTool / CronListTool.
 *
 * <ul>
 *   <li>{@code addCronTask}, {@code listAllCronTasks},
 *       {@code removeCronTasks}, {@code getCronFilePath}, {@code readCronTasks} and
 *       {@code writeCronTasks}; ID = 8-char hex UUID slice, durable file is
 *        with a
 *       {@code {"tasks": [...]}} envelope. Session-only teammate jobs carry
 *       their runtime {@code agentId}; durable jobs never persist it and instead
 *       persist creator session/PID/start-token affinity metadata.</li>
 * </ul>
 */
public final class CronStore {

    static final int MAX_JOBS = 50;
    static final int DEFAULT_MAX_AGE_DAYS = 7;

    private static final CopyOnWriteArrayList<CronJob> JOBS = new CopyOnWriteArrayList<>();
    private static volatile Path projectRootOverride;
    private static volatile boolean scheduledTasksEnabled;

    private CronStore() {}


    public static synchronized String add(String cron, String prompt, boolean recurring, boolean durable) {
        return add(cron, prompt, recurring, durable, (String) null);
    }
    /**
     * Teammate-aware form of {@code addCronTask}. The owner is runtime-only and
     * is deliberately omitted for durable jobs, matching the compatibility disk schema.
     */
    public static synchronized String add(String cron, String prompt, boolean recurring,
                                   boolean durable, String agentId) {
        return add(cron, prompt, recurring, durable, agentId, null);
    }

    /**
     * Application-facing model-carrying form: {@code model} is the optional
     * per-task model override the gateway schedule port threads through.
     */
    public static synchronized String addWithModel(String cron, String prompt,
                                   boolean recurring, boolean durable, String model) {
        return add(cron, prompt, recurring, durable, null,
            Instant.now().toEpochMilli(), null,
            UUID.randomUUID().toString().replace("-", "").substring(0, 8),
            null, false, null, null, null, model);
    }

    /**
     * Shared add-gate validation for the Cron tools and the gateway schedule
     * port: 5-field syntax, a fire time within the next year, and capacity
     * below {@link #MAX_JOBS}. Returns {@code null} when the job may be added;
     * otherwise the user-facing rejection message.
     */
    public static String validateNewJob(String cron) {
        if (!CronUtils.isValid(cron)) {
            return "Invalid cron expression '" + cron + "'. Expected 5 fields: M H DoM Mon DoW.";
        }
        if (CronUtils.nextRunMs(cron) == null) {
            return "Cron expression '" + cron
                + "' does not match any calendar date in the next year.";
        }
        if (JOBS.size() >= MAX_JOBS) {
            return "Too many scheduled jobs (max " + MAX_JOBS + "). Cancel one first.";
        }
        return null;
    }

/**
     * Durable creation form carrying.
     */
    public static synchronized String add(String cron, String prompt, boolean recurring,
                                   boolean durable, String agentId,
                                   String createdBySessionId) {
        String id = UUID.randomUUID().toString().replace("-", "").substring(0, 8);
        return add(cron, prompt, recurring, durable, agentId,
            Instant.now().toEpochMilli(), null, id, null, false,
            durable ? createdBySessionId : null,
            durable && createdBySessionId != null ? ProcessHandle.current().pid() : null,
            durable && createdBySessionId != null
                ? CronSchedulerLock.currentProcessStartToken() : null);
    }

    /**
     * Runtime scheduling form used by dynamic /loop wakeups. Their synthetic
     * one-shot cron needs an anchored {@code createdAt}, a {@code kind=loop}
     * discriminator, and the exact 8-hex ID generated by the loop runtime.
     */
    public static synchronized String add(String cron, String prompt, boolean recurring,
                                   boolean durable, String agentId, long createdAt,
                                   String kind, String id) {
        return add(cron, prompt, recurring, durable, agentId, createdAt, kind, id,
            null, false, null, null, null);
    }

    /** Full disk/runtime form used when restoring assistant-mode task metadata. */
    static synchronized String add(String cron, String prompt, boolean recurring,
                                   boolean durable, String agentId, long createdAt,
                                   String kind, String id, Long lastFiredAt,
                                   boolean permanent) {
        return add(cron, prompt, recurring, durable, agentId, createdAt, kind, id,
            lastFiredAt, permanent, null, null, null);
    }

    static synchronized String add(String cron, String prompt, boolean recurring,
                                   boolean durable, String agentId, long createdAt,
                                   String kind, String id, Long lastFiredAt,
                                   boolean permanent, String createdBySessionId,
                                   Long createdByPid, String createdByProcStart) {
        return add(cron, prompt, recurring, durable, agentId, createdAt, kind, id,
            lastFiredAt, permanent, createdBySessionId, createdByPid, createdByProcStart,
            null);
    }

    /** Canonical full form; {@code model} is the optional per-task model override. */
    static synchronized String add(String cron, String prompt, boolean recurring,
                                   boolean durable, String agentId, long createdAt,
                                   String kind, String id, Long lastFiredAt,
                                   boolean permanent, String createdBySessionId,
                                   Long createdByPid, String createdByProcStart,
                                   String model) {
        CronJob job = new CronJob(id, cron, prompt, recurring, durable,
            createdAt, lastFiredAt, permanent, durable ? null : agentId,
            durable ? null : kind,
            durable ? createdBySessionId : null,
            durable ? createdByPid : null,
            durable ? createdByProcStart : null,
            StringUtils.defaultIfBlank(model, null));
        JOBS.add(job);
        scheduledTasksEnabled = true;
        if (durable) persist();
        return id;
    }


    static synchronized boolean remove(String id) {
        boolean removed = JOBS.removeIf(j -> j.id().equals(id));
        if (removed) persist();
        return removed;
    }

    /** Removes a job by id from an application-layer scheduler callback. */
    public static boolean removeById(String id) {
        return remove(id);
    }

    /** Remove all jobs matching {@code predicate}; returns the number removed. */
    public static synchronized int removeWhere(Predicate<CronJob> predicate) {
        int before = JOBS.size();
        boolean durableRemoved = JOBS.stream().anyMatch(job -> job.durable() && predicate.test(job));
        JOBS.removeIf(predicate);
        int removed = before - JOBS.size();
        if (durableRemoved) persist();
        return removed;
    }


    public static List<CronJob> list() {
        return List.copyOf(JOBS);
    }


    static boolean scheduledTasksEnabled() {
        return scheduledTasksEnabled;
    }


    static boolean hasDurableTasksSync() {
        Path path = durablePath();
        if (!Files.isRegularFile(path)) return false;
        try {
            var root = JsonUtils.getMapper().readTree(path.toFile());
            return root != null && root.isObject()
                && root.path("tasks").isArray() && !root.path("tasks").isEmpty();
        } catch (IOException _) {
            return false;
        }
    }


    static Path durablePath() {
        return projectRoot().resolve(".claude").resolve("scheduled_tasks.json");
    }

    /** Load durable jobs from disk (call once at startup). */
    static synchronized void loadDurable() {
        JOBS.removeIf(CronJob::durable);
        Path path = durablePath();
        if (!Files.exists(path)) return;
        try {
            var root = JsonUtils.getMapper().readTree(path.toFile());
            if (!root.isObject() || !root.path("tasks").isArray()) return;
            for (var node : root.path("tasks")) {
                String id       = node.path("id").asText("");
                String cron     = node.path("cron").asText("");
                String prompt   = node.path("prompt").asText("");
                boolean recur   = node.path("recurring").asBoolean(false);
                long createdAt  = node.path("createdAt").asLong(0);
                Long lastFiredAt = node.has("lastFiredAt")
                    && node.get("lastFiredAt").canConvertToLong()
                    ? node.get("lastFiredAt").asLong() : null;
                boolean permanent = node.path("permanent").asBoolean(false);
                String createdBySessionId = node.path("createdBySessionId").isTextual()
                    ? node.path("createdBySessionId").asText() : null;
                Long createdByPid = node.path("createdByPid").canConvertToLong()
                    ? node.path("createdByPid").asLong() : null;
                String createdByProcStart = node.path("createdByProcStart").isTextual()
                    ? node.path("createdByProcStart").asText() : null;
                String model = node.path("model").isTextual()
                    && StringUtils.isNotBlank(node.path("model").asText())
                    ? node.path("model").asText() : null;
                if (!id.isEmpty() && !cron.isEmpty() && CronUtils.isValid(cron)) {
                    JOBS.add(new CronJob(id, cron, prompt, recur, true, createdAt,
                        lastFiredAt, permanent, null, null, createdBySessionId,
                        createdByPid, createdByProcStart, model));
                }
            }
        } catch (IOException _) {}
    }

    /** Persist the latest fire time of recurring durable tasks in one write. */
    static synchronized void markFired(List<String> ids, long firedAt) {
        if (ids == null || ids.isEmpty()) return;
        var wanted = Set.copyOf(ids);
        boolean changed = false;
        List<CronJob> replacement = new ArrayList<>(JOBS.size());
        for (CronJob job : JOBS) {
            if (wanted.contains(job.id()) && job.durable() && job.recurring()) {
                job = job.withLastFiredAt(firedAt);
                changed = true;
            }
            replacement.add(job);
        }
        if (changed) {
            JOBS.clear();
            JOBS.addAll(replacement);
            persist();
        }
    }

    /** Refreshes creator PID/start-token after resuming the same durable session. */
    static synchronized boolean refreshCreatorProcess(String sessionId, long pid,
                                                       String procStart) {
        if (StringUtils.isBlank(sessionId)) return false;
        boolean changed = false;
        List<CronJob> replacement = new ArrayList<>(JOBS.size());
        for (CronJob job : JOBS) {
            if (job.durable() && sessionId.equals(job.createdBySessionId())
                    && (!Objects.equals(job.createdByPid(), pid)
                        || !Objects.equals(job.createdByProcStart(), procStart))) {
                job = job.withCreatorProcess(pid, procStart);
                changed = true;
            }
            replacement.add(job);
        }
        if (changed) {
            JOBS.clear();
            JOBS.addAll(replacement);
            persist();
        }
        return changed;
    }

    private static void persist() {
        Path path = durablePath();
        try {
            Files.createDirectories(path.getParent());
            ObjectNode root = JsonUtils.getMapper().createObjectNode();
            var arr = root.putArray("tasks");
            for (CronJob j : JOBS) {
                if (!j.durable()) continue;
                ObjectNode n = JsonUtils.getMapper().createObjectNode();
                n.put("id", j.id());
                n.put("cron", j.cron());
                n.put("prompt", j.prompt());
                n.put("createdAt", j.createdAt());
                if (j.lastFiredAt() != null) n.put("lastFiredAt", j.lastFiredAt());
                if (j.recurring()) n.put("recurring", true);
                if (j.permanent()) n.put("permanent", true);
                if (j.createdBySessionId() != null) {
                    n.put("createdBySessionId", j.createdBySessionId());
                }
                if (j.createdByPid() != null) n.put("createdByPid", j.createdByPid());
                if (j.createdByProcStart() != null) {
                    n.put("createdByProcStart", j.createdByProcStart());
                }
                if (StringUtils.isNotBlank(j.model())) n.put("model", j.model());
                arr.add(n);
            }
            Path temp = Files.createTempFile(path.getParent(), ".scheduled_tasks-", ".tmp");
            Files.writeString(temp, JsonUtils.toPrettyJson(root) + "\n",
                StandardOpenOption.CREATE, StandardOpenOption.TRUNCATE_EXISTING);
            try {
                Files.move(temp, path, StandardCopyOption.ATOMIC_MOVE,
                    StandardCopyOption.REPLACE_EXISTING);
            } catch (IOException _) {
                Files.move(temp, path, StandardCopyOption.REPLACE_EXISTING);
            }
        } catch (IOException _) {}
    }

    private static Path projectRoot() {
        Path start = projectRootOverride;
        if (start == null) {
            start = CwdState.getOriginalCwd();
        }
        if (start == null) {
            start = Path.of(System.getProperty("user.dir"));
        }
        Path gitRoot = GitUtils.findCanonicalGitRoot(start);
        return (gitRoot != null ? gitRoot : start).toAbsolutePath().normalize();
    }

    static synchronized void configureProjectRootForTest(Path projectRoot) {
        projectRootOverride = projectRoot;
        JOBS.clear();
        scheduledTasksEnabled = false;
    }

    /** Runtime composition-root override used by SDK/headless schedulers. */
    static synchronized void configureProjectRootForRuntime(Path projectRoot) {
        if (projectRoot != null) projectRootOverride = projectRoot.toAbsolutePath().normalize();
    }

    public static synchronized void resetForTest() {
        JOBS.clear();
        projectRootOverride = null;
        scheduledTasksEnabled = false;
    }

    public record CronJob(String id, String cron, String prompt, boolean recurring,
                   boolean durable, long createdAt, Long lastFiredAt,
                   boolean permanent, String agentId, String kind,
                   String createdBySessionId, Long createdByPid,
                   String createdByProcStart, String model) {
        public CronJob(String id, String cron, String prompt, boolean recurring,
                       boolean durable, long createdAt, Long lastFiredAt,
                       boolean permanent, String agentId, String kind) {
            this(id, cron, prompt, recurring, durable, createdAt, lastFiredAt,
                permanent, agentId, kind, null, null, null, null);
        }

        CronJob withLastFiredAt(long firedAt) {
            return new CronJob(id, cron, prompt, recurring, durable, createdAt,
                firedAt, permanent, agentId, kind, createdBySessionId,
                createdByPid, createdByProcStart, model);
        }

        CronJob withCreatorProcess(long pid, String procStart) {
            return new CronJob(id, cron, prompt, recurring, durable, createdAt,
                lastFiredAt, permanent, agentId, kind, createdBySessionId,
                pid, procStart, model);
        }
    }
}
